/** Lowercase, strip accents/punctuation, collapse whitespace. "Bird-of-Paradise!" -> "bird of paradise" */
export function normalizeName(input: string): string {
  return input
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}
