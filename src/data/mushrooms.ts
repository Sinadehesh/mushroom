import type { Edibility, Mushroom, MushroomCategory } from '../core/types';

type Row = [
  id: string,
  commonName: string,
  scientificName: string,
  family: string,
  edibility: Edibility,
  aliases: string[],
  /** One direction is enough: look-alikes are matched both ways. */
  lookalikes: string[],
  fact: string,
];

function rows(category: MushroomCategory, list: Row[]): Mushroom[] {
  return list.map(([id, commonName, scientificName, family, edibility, aliases, lookalikes, fact]) => ({
    id,
    commonName,
    scientificName,
    family,
    category,
    edibility,
    aliases,
    lookalikes,
    fact,
  }));
}

